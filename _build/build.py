"""Rebuild the generated pages and the search index from content.py.

Run from anywhere:  python3 _build/build.py
Pages are plain HTML in the same markup style as the homepage, so they read fine
in any browser ever made; style.css and search.js only add polish on top.
"""
import html
import json
import os
import sys
import unicodedata

sys.dont_write_bytecode = True

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from content import SITE, SEASONS  # noqa: E402

# Blog cards are all the same size: CARD_LINES lines tall, counting the title line and the empty line under it.
# A card shows every item that fits; if a topic has more, the last two lines become an empty line and "View more".
CARD_LINES = 10
COLUMNS = 3
SUFFIX = " - James Croll Society"


def esc(s):
    """HTML-escape and turn anything non-ASCII into a decimal entity (understood by every browser ever made)."""
    return html.escape(s, quote=False).replace('"', "&quot;").encode("ascii", "xmlcharrefreplace").decode()


def fold(s):
    """Sort key: ignores case and accents, so Č sorts with C and É with E."""
    return "".join(c for c in unicodedata.normalize("NFD", s) if not unicodedata.combining(c)).casefold()


def runway_entries(runways):
    def rank(season):
        return SEASONS.index(season) if season in SEASONS else len(SEASONS)
    ordered = sorted(runways, key=lambda r: (r["year"], rank(r["season"]), fold(r["season"]), fold(r["brand"]), fold(r.get("line", ""))))
    return [{"title": f'{r["brand"]} - {r["year"]} - {r["season"]}' + (f' ({r["line"]})' if r.get("line") else ""),
             "href": r["href"]} for r in ordered]


def children(node):
    if "runways" in node:
        return runway_entries(node["runways"])
    return sorted(node.get("items", []), key=lambda n: fold(n["title"]))


def url(href, root):
    return href if "://" in href else root + href


def link(entry, root, hover=False):
    tip = f' title="{esc(entry["title"])}"' if hover else ""
    return f'<a href="{esc(url(entry["href"], root))}"{tip}>{esc(entry["title"])}</a>'


def crumbs(trail, root):
    parts = [f'<a href="{root}index.html">home</a>']
    for node in trail[:-1]:
        parts.append(f'<a href="{root}{node["href"]}">{esc(node.get("crumb", node["title"].lower()))}</a>')
    parts.append(esc(trail[-1].get("crumb", trail[-1]["title"].lower())))
    return " / ".join(parts)


def list_block(entries, root):
    rows = "\n".join(f"            {link(e, root)}<br>" for e in entries)
    return f'''    <center class="list">
        <font size="5">
{rows}
        </font>
    </center>'''


def cards_block(topics, root):
    room = CARD_LINES - 2
    rows = []
    for start in range(0, len(topics), COLUMNS):
        cells = []
        for topic in topics[start:start + COLUMNS]:
            items = children(topic)
            shown = items if len(items) <= room else items[:room - 2]
            lines = [f'                <a class="card-title" href="{esc(url(topic["href"], root))}"><font size="4"><b>{esc(topic["title"])}</b></font></a><br>',
                     '                <br>']
            lines += [f'                {link(e, root, hover=True)}<br>' for e in shown]
            if len(shown) < len(items):
                lines += ['                <br>',
                          f'                <a class="card-more" href="{esc(url(topic["href"], root))}"><i>View more</i></a><br>']
            cells.append('            <td width="33%" height="324" valign="top" align="center">\n'
                         + "\n".join(lines) + "\n            </td>")
        while len(cells) < COLUMNS:
            cells.append('            <td class="card-empty" width="33%"></td>')
        rows.append("        <tr>\n" + "\n".join(cells) + "\n        </tr>")
    return ('    <table class="cards" border="1" bordercolor="red" cellspacing="0" cellpadding="8" width="100%" align="center">\n'
            + "\n".join(rows) + "\n    </table>")


def write_page(node, trail):
    path = node["href"]
    root = "../" * path.count("/")
    title = node.get("tab", node["title"] + SUFFIX)
    heading = node.get("heading", node["title"])
    body = cards_block(children(node), root) if node["page"] == "cards" else list_block(children(node), root)
    note = f'\n\n    <center class="note-line"><font size="2">{node["note"]}</font></center>' if node.get("note") else ""
    page = f'''<!DOCTYPE html>
<!-- Generated by _build/build.py from _build/content.py. Edit those and rebuild, not this file. -->
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>{esc(title)}</title>
    <link rel="stylesheet" href="{root}style.css">
</head>

<body class="list-page{' wide' if node["page"] == "cards" else ''}" text="red" bgcolor="black" link="red" vlink="red" alink="red">

    <center class="crumbs"><font size="2">{crumbs(trail, root)}</font></center>

    <h1>
        <center>{esc(heading)}</center>
    </h1>

{body}{note}

</body>
</html>
'''
    full = os.path.join(REPO, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="ascii", newline="\n") as f:
        f.write(page)
    return path


def main():
    written, index = [], []

    def walk(nodes, trail):
        for node in nodes:
            here = trail + [node]
            entry = {"t": node["title"], "h": node["href"], "p": " / ".join(n["title"].lower() for n in trail)}
            if node.get("search"):
                entry["k"] = node["search"]
            index.append(entry)
            if node.get("page"):
                written.append(write_page(node, here))
            if "runways" in node:
                for e in runway_entries(node["runways"]):
                    index.append({"t": e["title"], "h": e["href"], "p": " / ".join(n["title"].lower() for n in here)})
            walk(node.get("items", []), here)

    walk(SITE, [])
    with open(os.path.join(REPO, "search-index.js"), "w", encoding="ascii", newline="\n") as f:
        f.write("// Generated by _build/build.py from _build/content.py.\n")
        f.write("var SEARCH_INDEX = " + json.dumps(index, ensure_ascii=True, indent=0) + ";\n")
    print(f"wrote {len(written)} pages and search-index.js ({len(index)} entries)")
    for p in written:
        print("  " + p)


if __name__ == "__main__":
    main()
